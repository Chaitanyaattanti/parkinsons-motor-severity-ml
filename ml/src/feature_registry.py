def export_feature_registry(config: PipelineConfig | None = None) -> pd.DataFrame:
    """Export the feature registry to CSV and JSON artifacts."""
    cfg = config or DEFAULT_CONFIG
    cfg.ensure_directories()
    
    rows = [f.to_dict() for f in FEATURE_REGISTRY]
    df_reg = pd.DataFrame(rows)
    
    csv_path = cfg.reports_features_dir / "feature_registry.csv"
    json_path = cfg.reports_features_dir / "feature_registry.json"
    
    df_reg.to_csv(csv_path, index=False)
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(rows, f, indent=2)
        
    return df_reg


if __name__ == "__main__":
    df = export_feature_registry()
    print(f"Feature registry exported: {len(df)} features defined across {df['category'].nunique()} categories.")

