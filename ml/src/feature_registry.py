@dataclass(frozen=True)
class FeatureMetadata:
    """Metadata specification for a single engineered feature."""

    name: str
    description: str
    category: str  # basic_statistics, first_difference, distribution_amplitude, temporal_quality, zero_crossing, peak_oscillation, frequency_domain, task_specific
    formula: str
    unit: str
    required_inputs: str
    validity_requirements: str
    task_applicability: str  # 'all' or comma-separated task names
    validation_status: str  # 'exploratory' or 'validated'

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


